async function loadStats() {
  try {
    const supabase = await createClient();
    const now = new Date().toISOString();
    const [events, persons, ensembles] = await Promise.all([
      supabase
        .from("events")
        .select("id", { count: "exact", head: true })
        .gte("start_datetime", now)
        // Gleiche Definition wie die App (EventRepository.fetchEvents):
        // nur status=scheduled, Beginn ab jetzt.
        .eq("status", "scheduled"),
      supabase.from("persons").select("id", { count: "exact", head: true }),
      supabase.from("ensembles").select("id", { count: "exact", head: true }),
    ]);
    return [
      { label: "kommende Konzerte", value: events.error ? null : events.count },
      { label: "Künstlerinnen und Künstler", value: persons.error ? null : persons.count },
      { label: "Ensembles", value: ensembles.error ? null : ensembles.count },
      { label: "Städte", value: CITIES.length },
    ].filter((stat): stat is { label: string; value: number } => typeof stat.value === "number" && stat.value > 0);
  } catch {
    return [];
  }
}

