}

private enum AppTab: Hashable {
    case home
    case search
    case map
    case calendar
    case profile
}

private struct DeepLinkSlug: Identifiable {
    let id: String
}

/// Lädt ein per Link geöffnetes Event (Push, Widget, Spotlight) und zeigt es.
private struct DeepLinkEventSheet: View {
    let slug: String
    let repository: any EventRepository
    let contentRepository: any ContentRepository
    @Environment(\.dismiss) private var dismiss
    @State private var event: ConcertEvent?
    @State private var failed = false

    var body: some View {
        NavigationStack {
            Group {
                if let event {
                    EventDetailView(event: event, repository: repository, contentRepository: contentRepository)
                } else if failed {
                    ContentUnavailableView("Konzert nicht gefunden", systemImage: "music.note", description: Text("Der Termin ist nicht mehr verfügbar."))
                } else {
                    ProgressView()
                }
            }
            .toolbar {
                ToolbarItem(placement: .topBarLeading) {
                    Button("Schließen", systemImage: "xmark") { dismiss() }
                }
            }
            // Ohne diese Ziele waren Profile, ähnliche Konzerte und Abo-Termine
            // auf per Link geöffneten Konzertseiten nicht antippbar.
            .navigationDestination(for: EntityRoute.self) { EntityDetailView(route: $0, repository: contentRepository) }
            .navigationDestination(for: ConcertEvent.self) { EventDetailView(event: $0, repository: repository, contentRepository: contentRepository) }
        }
        .task {
            event = try? await repository.event(slug: slug)
            failed = event == nil
        }
    }
}


private struct DeepLinkRoutingModifier: ViewModifier {
    @ObservedObject var deepLinks: DeepLinkRouter
    let environment: AppEnvironment
    @Binding var selection: AppTab
    @Binding var showsCoach: Bool
    @Binding var showsFriends: Bool
    @Binding var friendsSheetTab: FriendsHubTab
    let isReadyForInvite: Bool

    func body(content: Content) -> some View {
        content
            // Freundes-Einladung per Link: Freunde-Ansicht öffnen, die den Code
            // aus DeepLinkRouter.pendingFriendCode übernimmt – bei neuen
            // Nutzer:innen erst nach Anmeldung/Onboarding.
            .onChange(of: deepLinks.pendingFriendCode) { _, code in
                if code != nil && isReadyForInvite { friendsSheetTab = .friends; showsFriends = true }
            }
            .onChange(of: isReadyForInvite) { _, ready in
                if ready && deepLinks.pendingFriendCode != nil { friendsSheetTab = .friends; showsFriends = true }
            }
            .onChange(of: deepLinks.pendingFriendsTab) { _, tab in
                guard let tab else { return }
                friendsSheetTab = tab
                showsFriends = true
                deepLinks.pendingFriendsTab = nil
            }
            .sheet(isPresented: $showsFriends) {
                NavigationStack {
                    FriendsView(auth: environment.auth, repository: environment.restClient.map(UserRepository.init(client:)), initialTab: friendsSheetTab)
                        .toolbar { ToolbarItem(placement: .confirmationAction) { Button("Fertig") { showsFriends = false } } }
                }
            }
            .onChange(of: deepLinks.pendingTab) { _, tab in
                guard let tab else { return }
                switch tab {
                case "search": selection = .search
                case "map": selection = .map
                case "calendar": selection = .calendar
                case "profile": selection = .profile
                default: selection = .home
                }
                deepLinks.pendingTab = nil
            }
            .onChange(of: deepLinks.pendingCoach) { _, open in
                guard open else { return }
                showsCoach = true
                deepLinks.pendingCoach = false
            }
    }
}
