import CoreSpotlight
import SwiftUI

struct RootTabView: View {
    @Environment(\.scenePhase) private var scenePhase
    let environment: AppEnvironment

    @State private var selection: AppTab = .home
    // Ohne dieses @ObservedObject würde RootTabView.body nie neu ausgewertet,
    // wenn sich der Auth-Zustand ändert — .onChange(of: auth.userID) unten
    // bräuchte dafür eine body-Neuauswertung als Auslöser, die environment
    // als reines `let` sonst nicht liefert.
    @ObservedObject private var auth: AuthStore
    @StateObject private var favorites: FavoriteStore
    @StateObject private var follows: FollowStore
    @StateObject private var reportStore: ReportStore
    @StateObject private var cityStore: CityStore
    @StateObject private var genreFilterRouter = GenreFilterRouter()
    @AppStorage("didCompleteOnboarding") private var didCompleteOnboarding = false
    @State private var showsOnboarding = false
    // Generated by Claude Code — App startet unabhängig vom System-Modus
    // immer hell; "appearance" bleibt aber jederzeit über die
    // Profil-Einstellung auf "system"/"dark" umstellbar.
    @AppStorage("appearance") private var appearance = "light"
    @AppStorage(BiometricAuth.enabledStorageKey) private var biometricProtectionEnabled = false
    @State private var isBiometricUnlocked = !BiometricAuth.isEnabled
    @State private var isAuthenticatingBiometrics = false
    @State private var showsCoach = false
    @State private var showsFriends = false
    @State private var friendsSheetTab: FriendsHubTab = .activity
    @ObservedObject private var attendanceMonitor = AttendanceLocationMonitor.shared
    @ObservedObject private var deepLinks = DeepLinkRouter.shared

    init(environment: AppEnvironment) {
        self.environment = environment
        _selection = State(initialValue: ProcessInfo.processInfo.environment["KLANGRADAR_MARKETING_CAPTURE"] == "1" ? .profile : .home)
        _auth = ObservedObject(wrappedValue: environment.auth)
        _favorites = StateObject(wrappedValue: FavoriteStore(auth: environment.auth, repository: environment.restClient.map(UserRepository.init(client:))))
        _follows = StateObject(wrappedValue: FollowStore(auth: environment.auth, repository: environment.restClient.map(UserRepository.init(client:))))
        _reportStore = StateObject(wrappedValue: ReportStore(auth: environment.auth, repository: environment.restClient.map(UserRepository.init(client:))))
        _cityStore = StateObject(wrappedValue: CityStore(auth: environment.auth, repository: environment.restClient.map(UserRepository.init(client:))))
    }

    var body: some View {
        TabView(selection: $selection) {
            HomeView(
                repository: environment.events,
                contentRepository: environment.content,
                usesPreviewData: environment.isUsingPreviewData,
                auth: environment.auth,
                userRepository: environment.restClient.map(UserRepository.init(client:))
            )
            // Vorher .id(auth.userID) — zerstört und baut HomeViews komplette
            // NavigationStack neu auf, sobald sich die User-ID ändert (z. B.
            // Session-Wiederherstellung kurz nach dem Start). Genau dieser
            // Rebuild mitten im ersten Layout-Durchlauf verursacht einen
            // reproduzierbaren Absturz: "Layout requested for visible
            // navigation bar ... top item belongs to a different navigation
            // bar" (zwei UINavigationBar-Instanzen kurzzeitig gleichzeitig
            // aktiv). HomeViewModel reagiert bereits selbst per Combine auf
            // auth?.$state (siehe authCancellable in HomeViewModel.init) und
            // lädt bei Bedarf in-place neu — kein View-Rebuild nötig.
            .tag(AppTab.home)
            .tabItem {
                Label("Home", systemImage: "house")
            }



            SearchView(
                eventRepository: environment.events,
                contentRepository: environment.content
            )
                .tag(AppTab.search)
                .tabItem {
                    Label("Suche", systemImage: "magnifyingglass")
                }

            VenueMapView(repository: environment.content, eventRepository: environment.events, cityStore: cityStore)
                .tag(AppTab.map)
                .tabItem {
                    Label("Karte", systemImage: "map")
                }

            EventCalendarView(
                repository: environment.events,
                contentRepository: environment.content,
                auth: environment.auth,
                userRepository: environment.restClient.map(UserRepository.init(client:))
            )
                .tag(AppTab.calendar)
                .tabItem {
                    Label("Kalender", systemImage: "calendar")
                }

            ProfileView(
                usesPreviewData: environment.isUsingPreviewData,
                auth: environment.auth,
                userRepository: environment.restClient.map(UserRepository.init(client:)),
                editorialRepository: environment.restClient.map(EditorialRepository.init(client:)),
                eventRepository: environment.events,
                contentRepository: environment.content
            )
                .tag(AppTab.profile)
                .tabItem {
                    Label("Profil", systemImage: "person")
                }
        }
        .environmentObject(favorites)
        .environmentObject(follows)
        .environmentObject(reportStore)
        .environmentObject(genreFilterRouter)
        .environmentObject(cityStore)
        .overlay(alignment: .bottomTrailing) {
            if selection == .home, environment.restClient != nil, !shouldShowBiometricLock {
                Button {
                    showsCoach = true
                } label: {
                    Image("KlangradarLogo")
                        .resizable()
                        .scaledToFill()
                        .frame(width: 56, height: 56)
                        .clipShape(.rect(cornerRadius: 17, style: .continuous))
                        .overlay {
                            RoundedRectangle(cornerRadius: 17, style: .continuous)
                                .stroke(.white.opacity(0.76), lineWidth: 1)
                        }
                        .shadow(color: .black.opacity(0.16), radius: 11, y: 5)
                }
                .buttonStyle(RootCoachButtonStyle())
                .accessibilityLabel("Klangradar KI öffnen")
                .accessibilityHint("Öffnet die persönliche Klangradar KI in einer halbhohen Ansicht")
                .padding(.trailing, 18)
                .padding(.bottom, 88)
                .transition(.opacity.combined(with: .scale(scale: 0.96, anchor: .bottomTrailing)))
                .zIndex(20)
            }
        }
        .onChange(of: genreFilterRouter.pending) { _, pending in
            if pending != nil { selection = .search }
        }
        // Deep Links (Freunde, Siri-Tabs, KI) in einem eigenen Modifier:
        // die lange Modifier-Kette überforderte sonst die Typprüfung des
        // Compilers auf dem CI-Rechner ("unable to type-check ... in
        // reasonable time").
        .modifier(DeepLinkRoutingModifier(
            deepLinks: deepLinks,
            environment: environment,
            selection: $selection,
            showsCoach: $showsCoach,
            showsFriends: $showsFriends,
            friendsSheetTab: $friendsSheetTab,
            isReadyForInvite: isReadyForInvite
        ))
        .task {
            await auth.bootstrap()
            await refreshOnboardingGate()
            await unlockWithBiometricsIfNeeded()
        }
        .onChange(of: auth.userID) { _, _ in
            Task {
                await refreshOnboardingGate()
                await favorites.load()
                await follows.load()
                await SocialStore.shared.refresh()
                await cityStore.load()
                await PlusStore.shared.refreshServerStatus()
                await attendanceMonitor.refresh()
            }
        }
        .task { await favorites.load() }
        .onChange(of: favorites.ids) { _, ids in
            Task { await ConcertSync.shared.refresh(favoriteIDs: ids, repository: environment.events) }
        }
        .onContinueUserActivity(CSSearchableItemActionType) { activity in
            // Tipp auf ein gemerktes Konzert in der iPhone-Suche (Spotlight).
            if let identifier = activity.userInfo?[CSSearchableItemActivityIdentifier] as? String, identifier.hasPrefix("event:") {
                DeepLinkRouter.shared.handle(route: "/event/\(identifier.dropFirst(6))")
            }
        }
        .sheet(item: Binding(
            get: { deepLinks.pendingEventSlug.map(DeepLinkSlug.init) },
            set: { deepLinks.pendingEventSlug = $0?.id }
        )) { link in
            DeepLinkEventSheet(slug: link.id, repository: environment.events, contentRepository: environment.content)
                // Sheets erben die environmentObjects nicht (sie hängen außen
                // an der View): ohne sie stürzte jede per Link geöffnete
                // Konzertseite in EventDetailView ab (FavoriteStore fehlt).
                .environmentObject(favorites)
                .environmentObject(follows)
                .environmentObject(reportStore)
                .environmentObject(genreFilterRouter)
                .environmentObject(cityStore)
        }
        .task {
            EngagementLogger.shared.configure(client: environment.restClient, auth: environment.auth)
            PartnerStore.shared.configure(client: environment.restClient)
        }
        .task {
            PlusStore.shared.configure(client: environment.restClient, auth: environment.auth)
            PlusStore.shared.start()
        }
        .task { DiagnosticsReporter.shared.start(client: environment.restClient, auth: environment.auth) }
        .task { PushRegistration.shared.configure(client: environment.restClient, auth: environment.auth) }
        .task { await PromotedEventsStore.shared.load(client: environment.restClient, repository: environment.events) }
        .task { await follows.load() }
        .task {
            SocialStore.shared.configure(auth: environment.auth, repository: environment.restClient.map(UserRepository.init(client:)), eventRepository: environment.events)
            await SocialStore.shared.refresh()
        }
        .task { await cityStore.load() }
        .task {
            // Nutzerwunsch: automatische, standortbasierte Erkennung "warst
            // du bei diesem gemerkten Konzert?" — läuft passiv im
            // Hintergrund (Geofencing), markiert nie selbstständig, fragt
            // immer per eigenem Popup nach (siehe AttendanceLocationMonitor,
            // .sheet unten). requestAlwaysAuthorizationIfNeeded() ist ein
            // No-Op, solange der Zugriff bereits "Immer" ist oder verweigert
            // wurde — kein wiederholtes Nachfragen.
            attendanceMonitor.configure(repository: environment.restClient.map(UserRepository.init(client:)), auth: auth)
            attendanceMonitor.requestAlwaysAuthorizationIfNeeded()
            await attendanceMonitor.refresh()
        }
        .sheet(item: $attendanceMonitor.pendingConfirmation) { pending in
            AttendanceConfirmationPrompt(eventTitle: pending.title) { accepted in
                Task { await attendanceMonitor.confirmPendingAttendance(accepted: accepted) }
            }
            .presentationDetents([.height(260)])
        }
        .fullScreenCover(isPresented: $showsOnboarding) {
            OnboardingView(
                auth: auth,
                repository: environment.restClient.map(UserRepository.init(client:))
            ) {
                didCompleteOnboarding = true
                showsOnboarding = false
            }
            // Generated by Claude Code — FollowCategoryStepView (Onboarding-
            // Schritt "Folgen") liest FollowStore per @EnvironmentObject;
            // ohne explizites Reattach hier stürzt die App beim Erreichen
            // dieses Schritts mit "No ObservableObject of type FollowStore
            // found" ab, weil fullScreenCover-Inhalte das .environmentObject
            // der präsentierenden View nicht zuverlässig erben.
            .environmentObject(follows)
        }
        .whatsNewSheet(blocked: showsOnboarding || auth.isCompletingPasswordRecovery)
        .sheet(isPresented: $auth.isCompletingPasswordRecovery) {
            PasswordResetCompletionView(auth: auth)
        }
        .overlay {
            if showsCoach, let repository = environment.restClient.map(UserRepository.init(client:)) {
                // Eigenes Panel statt .sheet: unter iOS 26 werden Sheets mit
                // Teil-Detents als schwebende, eingerückte Karte gezeigt
                // (Hintergrund seitlich/unten sichtbar). Das Panel füllt die
                // volle Breite und reicht bis zum unteren Bildschirmrand.
                CoachPanel(title: "Klangradar KI", isPresented: $showsCoach) {
                    NavigationStack {
                        KlangradarCoachView(
                            auth: auth,
                            repository: repository,
                            eventRepository: environment.events,
                            contentRepository: environment.content,
                            startsInChat: true,
                            showsDismissButton: false
                        )
                        .modifier(ClearNavigationContainerBackground())
                        .toolbar(.hidden, for: .navigationBar)
                    }
                    .environmentObject(favorites)
                    .environmentObject(cityStore)
                }
                .zIndex(50)
                .transition(.move(edge: .bottom))
            }
        }
        .animation(.spring(duration: 0.35, bounce: 0.05), value: showsCoach)
        .alert("Link konnte nicht geöffnet werden", isPresented: callbackErrorBinding) {
            Button("OK", role: .cancel) { auth.callbackErrorMessage = nil }
        } message: {
            Text(auth.callbackErrorMessage ?? "Bitte fordere einen neuen Link an.")
        }
        .onOpenURL { url in
            if DeepLinkRouter.shared.handle(url: url) { return }
            if url.scheme == AuthService.callbackScheme, url.host == "auth-callback" {
                showsOnboarding = false
                Task { await auth.handleAuthCallback(url) }
                return
            }
            let path = url.path.lowercased()
            if path.contains("search") { selection = .search }
            else if path.contains("map") || path.contains("venue") { selection = .map }
            else if path.contains("calendar") { selection = .calendar }
            else if path.contains("profile") || path.contains("admin") { selection = .profile }
            else { selection = .home }
        }
        .preferredColorScheme(preferredColorScheme)
        .overlay {
            if shouldShowBiometricLock {
                BiometricLockView(isAuthenticating: isAuthenticatingBiometrics) {
                    Task { await unlockWithBiometricsIfNeeded() }
                }
                .transition(.opacity)
                .zIndex(100)
            }
        }
        .onChange(of: scenePhase) { _, phase in
            if phase == .background, biometricProtectionEnabled, case .authenticated = auth.state {
                isBiometricUnlocked = false
            } else if phase == .active {
                Task {
                    await unlockWithBiometricsIfNeeded()
                    await attendanceMonitor.refresh()
                    await PromotedEventsStore.shared.refreshIfStale(client: environment.restClient, repository: environment.events)
                    await ConcertSync.shared.refresh(favoriteIDs: favorites.ids, repository: environment.events)
                }
            }
        }
        .onChange(of: biometricProtectionEnabled) { _, enabled in
            isBiometricUnlocked = !enabled
            if enabled { Task { await unlockWithBiometricsIfNeeded() } }
        }
    }

    private var callbackErrorBinding: Binding<Bool> {
        Binding(
            get: { auth.callbackErrorMessage != nil },
            set: { if !$0 { auth.callbackErrorMessage = nil } }
        )
    }

    private var shouldShowBiometricLock: Bool {
        guard case .authenticated = auth.state else { return false }
        return biometricProtectionEnabled && !isBiometricUnlocked
    }

    @MainActor
    private func unlockWithBiometricsIfNeeded() async {
        guard shouldShowBiometricLock, !isAuthenticatingBiometrics else { return }
        isAuthenticatingBiometrics = true
        defer { isAuthenticatingBiometrics = false }
        if (try? await BiometricAuth.authenticate(reason: "Klangradar entsperren")) == true {
            withAnimation(.easeOut(duration: 0.2)) { isBiometricUnlocked = true }
        }
    }

    /// Einladungslinks erst nach Anmeldung bzw. abgeschlossenem Onboarding
    /// übernehmen (Freunde-Ausbau 28.10.2026).
    private var isReadyForInvite: Bool {
        guard auth.userID != nil, !showsOnboarding else { return false }
        if case .authenticated = auth.state { return true }
        return didCompleteOnboarding
    }

    private var preferredColorScheme: ColorScheme? {
        switch appearance { case "light": .light; case "dark": .dark; default: nil }
    }

    /// Zeigt das Onboarding, solange es lokal noch nie durchlaufen wurde
    /// (Gast-Skip zählt hier auch — "Ohne Account fortfahren" beendet den
    /// Flow), UND zusätzlich immer dann, wenn ein echter (nicht-anonymer)
    /// Account existiert, dessen `profiles.onboarding_completed` serverseitig
    /// noch nicht gesetzt ist — deckt Neuinstall/anderes Gerät mit
    /// bestehendem Account ab, ohne den lokalen Gast-Skip zu verlieren.
    private func refreshOnboardingGate() async {
        guard !auth.isCompletingPasswordRecovery else {
            showsOnboarding = false
            return
        }
        guard
            case .authenticated = auth.state,
            let userID = auth.userID,
            let token = auth.accessToken,
            let repository = environment.restClient.map(UserRepository.init(client:))
        else {
            showsOnboarding = !didCompleteOnboarding
            return
        }
        let completed = (try? await repository.isOnboardingCompleted(userID: userID, token: token)) ?? true
        // Ein bestehender Nutzer, der sich bewusst aus dem Profil anmeldet,
        // darf nicht zurück in den Registrierungsflow gezwungen werden. Das
        // serverseitige Flag hilft nur auf einer frischen Installation; ein
        // lokal bereits abgeschlossenes (auch als Gast übersprungenes)
        // Onboarding hat Vorrang.
        showsOnboarding = !didCompleteOnboarding && !completed
    }
}

// Erzwingt kantenbündiges Sheet-Sizing (kein "Form"-Rand auf iPad) ab iOS 18,
// unverändertes Verhalten darunter — .presentationSizing(_:) existiert erst
// ab iOS 18, ein reiner `if #available`-Ausdruck als ViewModifier-Body lässt
// sich nicht direkt inline in eine Modifier-Kette schreiben, deshalb als
// eigener Typ.
private struct ClearNavigationContainerBackground: ViewModifier {
    func body(content: Content) -> some View {
        if #available(iOS 18.0, *) {
            content.containerBackground(for: .navigation) { Color.clear }
        } else {
            content
        }
    }
}

private struct CoachPanel<Content: View>: View {
    let title: String
    @Binding var isPresented: Bool
    @ViewBuilder let content: Content
    @State private var expanded = false
    @State private var dragTranslation: CGFloat = 0
    @Environment(\.colorScheme) private var colorScheme

    private let shape = UnevenRoundedRectangle(topLeadingRadius: 28, topTrailingRadius: 28, style: .continuous)

    var body: some View {
        GeometryReader { geo in
            let halfHeight = geo.size.height * 0.58 + geo.safeAreaInsets.bottom
            let fullHeight = geo.size.height * 0.94 + geo.safeAreaInsets.bottom
            let base = expanded ? fullHeight : halfHeight
            // Höhe folgt dem Finger stufenlos; nach oben bis zur vollen Höhe.
            let height = min(max(base - dragTranslation, 80), fullHeight)
            VStack(spacing: 0) {
                header(halfHeight: halfHeight, fullHeight: fullHeight, base: base)
                content
            }
            .frame(width: geo.size.width, height: height, alignment: .top)
            .background {
                shape
                    .fill(KlangradarTheme.accent.opacity(colorScheme == .dark ? 0.18 : 0.10))
                    .background { KlangradarBackground().clipShape(shape) }
                    .shadow(color: .black.opacity(0.18), radius: 16, y: -4)
                    .ignoresSafeArea(edges: .bottom)
            }
            .clipShape(shape)
            .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .bottom)
            .ignoresSafeArea(edges: .bottom)
        }
    }

    // Griff + Titelzeile bilden EINEN einheitlichen Kopfbereich (kein
    // Navigationsleisten-Streifen mehr) und sind zugleich die Ziehfläche.
    private func header(halfHeight: CGFloat, fullHeight: CGFloat, base: CGFloat) -> some View {
        VStack(spacing: 0) {
            Capsule()
                .fill(.secondary.opacity(0.45))
                .frame(width: 38, height: 5)
                .padding(.top, 8)
            ZStack {
                Text(title).font(.headline)
                HStack {
                    Spacer()
                    Button("Fertig") { isPresented = false }
                        .fontWeight(.semibold)
                        .padding(.horizontal, 14)
                        .padding(.vertical, 7)
                        .glassPill()
                }
            }
            .padding(.horizontal, 16)
            .padding(.top, 6)
            .padding(.bottom, 8)
        }
        .frame(maxWidth: .infinity)
        .contentShape(.rect)
        .gesture(
            DragGesture(minimumDistance: 6)
                .onChanged { dragTranslation = $0.translation.height }
                .onEnded { value in
                    let final = min(max(base - value.translation.height, 0), fullHeight)
                    let projected = min(max(base - value.predictedEndTranslation.height, 0), fullHeight)
                    withAnimation(.spring(duration: 0.3)) {
                        if projected < halfHeight * 0.7 { isPresented = false }
                        else if final > (halfHeight + fullHeight) / 2 || projected > (halfHeight + fullHeight) / 2 { expanded = true }
                        else { expanded = false }
                        dragTranslation = 0
                    }
                }
        )
    }
}

private extension View {
    @ViewBuilder func glassPill() -> some View {
        if #available(iOS 26.0, *) {
            self.glassEffect(.regular.interactive(), in: Capsule())
        } else {
            self.background(.thinMaterial, in: Capsule())
        }
    }
}

private struct RootCoachButtonStyle: ButtonStyle {
    func makeBody(configuration: Configuration) -> some View {
        configuration.label
            .scaleEffect(configuration.isPressed ? 0.96 : 1)
            .opacity(configuration.isPressed ? 0.9 : 1)
            .animation(.easeOut(duration: 0.14), value: configuration.isPressed)
    }
}

