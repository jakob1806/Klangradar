import SwiftUI

/// Aus ProfileView.swift extrahiert, damit dieselbe Ansicht sowohl von
/// Profil → Interessen (per NavigationLink, mit eigenem Navigationstitel)
/// als auch als eingebetteter Onboarding-Schritt (ohne umgebenden
/// NavigationStack — `.navigationTitle` bleibt dort einfach wirkungslos)
/// verwendet werden kann, ohne die Interessen-Logik zu duplizieren.
struct InterestsView: View {
    @ObservedObject var auth: AuthStore
    let repository: UserRepository?
    /// Onboarding-Schritt "Interessen" zeigt bewusst nur Genres — Werke
    /// entfallen dort komplett, Personen/Ensembles/Venues bekommen eigene
    /// Folgen-Schritte (siehe FollowCategoryStepView). Ohne Vorgabe (Profil
    /// → Interessen) bleibt der volle Kategorie-Umschalter wie bisher.
    var fixedCategory: InterestCategory? = nil
    @State private var category: InterestCategory = .genre
    @State private var options: [InterestOption] = []
    @State private var selected: Set<String> = []
    @State private var searchText = ""
    /// Personen/Ensembles/Orte werden serverseitig gesucht (dieselbe RPC wie
    /// im Onboarding), weil lokal nur die Top-Vorschläge geladen sind.
    @State private var searchResults: [InterestOption]?

    private var filteredOptions: [InterestOption] {
        if searchText.isEmpty { return options }
        if showsThumbnails, let searchResults { return searchResults }
        return options.filter { $0.label.localizedStandardContains(searchText) }
    }

    private var showsThumbnails: Bool {
        category == .person || category == .ensemble || category == .venue
    }

    private var entityKind: EntityKind {
        switch category {
        case .person: .person
        case .ensemble: .ensemble
        case .venue: .venue
        case .genre, .work: .work
        }
    }

    var body: some View {
        if fixedCategory != nil {
            onboardingChipBody
        } else {
            settingsListBody
        }
    }

    /// Generated by Claude Code — Genres im Onboarding: zuerst volle
    /// List-Zeilen, dann ein Chip-Fluss. Nutzerfeedback 28.10.2026: sah
    /// "nicht so gut aus". Jetzt ein 2-spaltiges Kachel-Grid mit Symbol und
    /// kurzer Beschreibung je Genre; Profil → Interessen bleibt die Liste.
    private var onboardingChipBody: some View {
        genreGrid
            .onAppear { if let fixedCategory { category = fixedCategory } }
            .task(id: category) { searchText = ""; await load() }
    }

    private var genreSubtitle: String {
        if fixedCategory == nil {
            return selected.isEmpty ? "Wähle, was dich interessiert. Danach richten sich deine Empfehlungen." : "\(selected.count) ausgewählt"
        }
        return selected.count < 3
            ? "Wähle mindestens drei Bereiche. Danach richten sich deine Empfehlungen."
            : "\(selected.count) ausgewählt. Du kannst das jederzeit im Profil ändern."
    }

    private var genreGrid: some View {
        ScrollView {
            VStack(spacing: 20) {
                VStack(spacing: 6) {
                    Text("Was hörst du gern?")
                        .font(.title2.bold())
                    Text(genreSubtitle)
                        .font(.footnote)
                        .foregroundStyle(.secondary)
                        .multilineTextAlignment(.center)
                        .contentTransition(.numericText())
                }
                .frame(maxWidth: .infinity)

                LazyVGrid(columns: [GridItem(.flexible(), spacing: 12), GridItem(.flexible(), spacing: 12)], spacing: 12) {
                    ForEach(options) { option in
                        GenreTile(option: option, isSelected: selected.contains(option.id)) { toggle(option.id) }
                    }
                }
            }
            .padding(.horizontal, 20)
            .padding(.top, 12)
            .padding(.bottom, 12)
            .animation(.snappy(duration: 0.2), value: selected)
        }
    }

    /// Profil → Interessen im Stil des Onboardings (Nutzerwunsch
    /// 29.10.2026): Genres als Kachel-Grid, Personen/Ensembles/Orte als
    /// Bild-Grid mit Folgen-Häkchen (derselbe Baustein wie im Onboarding),
    /// Werke weiter als durchsuchbare Liste.
    private var settingsListBody: some View {
        VStack(spacing: 0) {
            ScrollView(.horizontal) {
                HStack(spacing: 8) {
                    ForEach(InterestCategory.allCases, id: \.self) { item in
                        Button {
                            Haptics.light()
                            category = item
                        } label: {
                            Label(item.title, systemImage: item.systemImage)
                                .font(.subheadline.weight(.semibold))
                                .padding(.horizontal, 14).padding(.vertical, 9)
                                .background(category == item ? AnyShapeStyle(KlangradarTheme.accent) : AnyShapeStyle(Color(.secondarySystemBackground)), in: .capsule)
                                .foregroundStyle(category == item ? .white : .primary)
                        }
                        .buttonStyle(.plain)
                        .accessibilityAddTraits(category == item ? .isSelected : [])
                    }
                }
                .padding(.horizontal, 20)
                .padding(.vertical, 10)
            }
            .scrollIndicators(.hidden)

            switch category {
            case .genre:
                genreGrid
                    .task { searchText = ""; await load() }
            case .person, .ensemble, .venue:
                FollowCategoryStepView(auth: auth, repository: repository, category: category)
                    .id(category)
            case .work:
                workList
            }
        }
        .navigationTitle("Interessen")
        .navigationBarTitleDisplayMode(.inline)
    }

    private var workList: some View {
        List {
            Section("Werke · \(selected.count) ausgewählt") {
                ForEach(filteredOptions) { option in
                    Button { toggle(option.id) } label: {
                        HStack(spacing: 12) {
                            Text(option.label).foregroundStyle(.primary)
                            Spacer()
                            Image(systemName: selected.contains(option.id) ? "checkmark.circle.fill" : "circle")
                                .font(.system(size: 28, weight: .regular))
                                .frame(width: 44, height: 44)
                                .foregroundStyle(selected.contains(option.id) ? KlangradarTheme.accent : .secondary)
                        }
                    }
                }
            }
        }
        .searchable(text: $searchText, prompt: "Werke durchsuchen")
        .task { searchText = ""; await load() }
    }

    private func load() async {
        guard let repository else { return }
        // Personen/Ensembles/Orte nach Bekanntheit statt alphabetisch
        // (Nutzerwunsch 28.10.2026); Genres und Werke bleiben wie bisher.
        if showsThumbnails, let ranked = try? await repository.followSuggestions(category, limit: 200, token: auth.accessToken), !ranked.isEmpty {
            options = ranked
        } else {
            options = (try? await repository.interestOptions(category)) ?? []
        }
        guard let id = auth.userID, let token = auth.accessToken else { return }
        selected = (try? await repository.selectedInterests(category, userID: id, token: token)) ?? []
    }

    private func toggle(_ id: String) {
        guard let repository, let userID = auth.userID, let token = auth.accessToken else { return }
        let newValue = !selected.contains(id)
        if newValue { selected.insert(id) } else { selected.remove(id) }
        // Generated by Claude Code — sehr leichter Tick pro Auswahl; im
        // Onboarding-Genres-Schritt (fixedCategory gesetzt) zusätzlich ein
        // etwas deutlicherer Impuls, sobald die empfohlene Mindestanzahl
        // (3) gerade erreicht wird.
        Haptics.light()
        if fixedCategory != nil, newValue, selected.count == 3 {
            Haptics.confirm()
        }
        Task { try? await repository.setInterest(category, id: id, selected: newValue, userID: userID, token: token) }
    }
}

/// Kachel für ein Genre im Onboarding: Symbol im farbigen Kreis, Name und
/// eine kurze Beschreibung; ausgewählt füllt sich die Kachel in der
/// Akzentfarbe.
private struct GenreTile: View {
    let option: InterestOption
    let isSelected: Bool
    let action: () -> Void

    private var style: (symbol: String, color: Color, caption: String) {
        switch option.label.lowercased() {
        case "oper": ("theatermasks.fill", .red, "Musiktheater und Operette")
        case "konzert": ("music.note.house.fill", .indigo, "Sinfonik, Solo und mehr")
        case "chormusik": ("person.3.fill", .teal, "Chöre und Vokalensembles")
        case "kirchenmusik": ("building.columns.fill", .brown, "Messen, Kantaten, Oratorien")
        case "kammermusik": ("music.quarternote.3", .orange, "Trio, Quartett, kleine Besetzung")
        case "liederabend": ("music.mic", .pink, "Stimme und Klavier")
        case "orchester": ("music.note.list", .blue, "Große Besetzung")
        case "orgel": ("pianokeys", .gray, "Orgelkonzerte und -nächte")
        case "jazz": ("music.note", .purple, "Jazz und Crossover")
        case "neue musik": ("waveform", .mint, "Zeitgenössisch und experimentell")
        case "familienkonzert": ("figure.2.and.child.holdinghands", .green, "Für Groß und Klein")
        case "kinder": ("balloon.2.fill", .yellow, "Konzerte für Kinder")
        default: ("music.note", KlangradarTheme.accent, "")
        }
    }

    var body: some View {
        Button(action: action) {
            HStack(spacing: 12) {
                Image(systemName: style.symbol)
                    .font(.system(size: 17, weight: .semibold))
                    .foregroundStyle(isSelected ? KlangradarTheme.accent : .white)
                    .frame(width: 40, height: 40)
                    .background(isSelected ? AnyShapeStyle(.white) : AnyShapeStyle(style.color.gradient), in: .circle)
                VStack(alignment: .leading, spacing: 2) {
                    Text(option.label)
                        .font(.subheadline.weight(.semibold))
                        .lineLimit(1)
                        .minimumScaleFactor(0.8)
                    if !style.caption.isEmpty {
                        Text(style.caption)
                            .font(.caption2)
                            .foregroundStyle(isSelected ? AnyShapeStyle(.white.opacity(0.85)) : AnyShapeStyle(.secondary))
                            .lineLimit(2)
                            .fixedSize(horizontal: false, vertical: true)
                    }
                }
                Spacer(minLength: 0)
            }
            .foregroundStyle(isSelected ? .white : .primary)
            .padding(12)
            .frame(maxWidth: .infinity, minHeight: 72, alignment: .leading)
            .background(isSelected ? AnyShapeStyle(KlangradarTheme.accent) : AnyShapeStyle(Color(.secondarySystemBackground)), in: .rect(cornerRadius: 18, style: .continuous))
            .overlay(alignment: .topTrailing) {
                if isSelected {
                    Image(systemName: "checkmark.circle.fill")
                        .font(.system(size: 16))
                        .foregroundStyle(.white)
                        .padding(8)
                }
            }
        }
        .buttonStyle(.plain)
        .accessibilityAddTraits(isSelected ? .isSelected : [])
    }
}
